DO $$
DECLARE
  column_info record;
BEGIN
  FOR column_info IN
    SELECT table_name, column_name
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND data_type = 'text'
      AND (table_name, column_name) IN (
        ('events', 'host_id'),
        ('invitations', 'claimed_by'),
        ('tickets', 'attendee_id'),
        ('tickets', 'checked_in_by'),
        ('scan_logs', 'scanner_id')
      )
  LOOP
    EXECUTE format(
      'ALTER TABLE public.%I ALTER COLUMN %I TYPE uuid USING NULLIF(%I, '''')::uuid',
      column_info.table_name,
      column_info.column_name,
      column_info.column_name
    );
  END LOOP;
END;
$$;

DO $$
DECLARE
  column_info record;
BEGIN
  FOR column_info IN
    SELECT table_name, column_name
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND data_type = 'time with time zone'
      AND (table_name, column_name) IN (
        ('profiles', 'created_at'),
        ('events', 'created_at'),
        ('invitations', 'claimed_at'),
        ('invitations', 'created_at'),
        ('tickets', 'checked_in_at'),
        ('tickets', 'created_at'),
        ('scan_logs', 'created_at')
      )
  LOOP
    EXECUTE format(
      'ALTER TABLE public.%I ALTER COLUMN %I TYPE timestamptz USING ((CURRENT_DATE + %I::time) AT TIME ZONE current_setting(''TimeZone''))',
      column_info.table_name,
      column_info.column_name,
      column_info.column_name
    );
  END LOOP;
END;
$$;

